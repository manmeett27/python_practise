'''2. The "Savings Goal" Tracker
Goal: Practice the while loop.

Task: Start with balance = 0. Ask the user "How much did you save today?".

Task: Keep asking (looping) until the balance is 100 or more.

Output: Once they hit 100, print "Goal reached! Total savings: $[balance]".'''

balance = 0
while balance != 100:
    balance = balance+1
print(f"Goal reached! Total savings: {balance}")